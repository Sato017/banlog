-- BanLog · Supabase schema
-- Run this in the Supabase SQL Editor once per project.

create table if not exists public.anime_cache (
  id integer primary key,
  title_native text,
  title_romaji text,
  title_chinese text,
  description text,
  synopsis_chinese text,
  cover_url text,
  format text,
  genres text[] not null default '{}',
  episodes integer,
  season_year integer,
  updated_at timestamptz not null default now()
);

create table if not exists public.watch_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  anime_id integer not null references public.anime_cache(id) on delete cascade,
  status text not null default 'watched' check (status = 'watched'),
  watched_at timestamptz not null default now(),
  unique (user_id, anime_id)
);

create index if not exists watch_records_user_watched_at_idx
  on public.watch_records (user_id, watched_at desc);

create index if not exists watch_records_anime_id_idx
  on public.watch_records (anime_id);

-- Keep anime_cache.updated_at current for server-side upserts.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists anime_cache_touch_updated_at on public.anime_cache;
create trigger anime_cache_touch_updated_at
before update on public.anime_cache
for each row execute function public.touch_updated_at();

-- Row Level Security
alter table public.anime_cache enable row level security;
alter table public.watch_records enable row level security;

-- Shared AniList cache: authenticated users may read it.
-- Writes are performed only by the server using the service_role key.
drop policy if exists "Authenticated users can read anime cache" on public.anime_cache;
create policy "Authenticated users can read anime cache"
  on public.anime_cache
  for select
  to authenticated
  using (true);

-- Each user can only read/create/update/delete their own watch records.
drop policy if exists "Users can read their own watch records" on public.watch_records;
create policy "Users can read their own watch records"
  on public.watch_records
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own watch records" on public.watch_records;
create policy "Users can insert their own watch records"
  on public.watch_records
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their own watch records" on public.watch_records;
create policy "Users can update their own watch records"
  on public.watch_records
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own watch records" on public.watch_records;
create policy "Users can delete their own watch records"
  on public.watch_records
  for delete
  to authenticated
  using (auth.uid() = user_id);

-- Privileges: authenticated users can read shared cache and manage their records.
grant usage on schema public to authenticated;
grant select on public.anime_cache to authenticated;
revoke insert, update, delete on public.anime_cache from anon, authenticated;
grant select, insert, update, delete on public.watch_records to authenticated;
grant usage, select on all sequences in schema public to authenticated;
